"""Build (and optionally push) a self-contained Kaggle script kernel that runs pipeline stages.

The package (src/, scripts/, configs/) is embedded as a base64 zip, so no dataset upload is
needed for code changes. Outputs must be written under /kaggle/working.

Examples:
  python scripts/kaggle_kernel.py --name knee-inspect --internet \
      --cmd "scripts/inspect_data.py --header-scan -1 --out /kaggle/working/inspect" --push
  kaggle kernels status <user>/knee-inspect
  kaggle kernels output <user>/knee-inspect -p results/kaggle/knee-inspect
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import shlex
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPETITION = "rsna-knee-abnormality-detection"
INCLUDE = ["src", "scripts", "configs"]

TEMPLATE = '''"""Auto-generated by scripts/kaggle_kernel.py: runs rsna-knee pipeline stages on Kaggle."""
import base64, io, os, subprocess, sys, time, zipfile

PAYLOAD = "{payload}"
PIP = {pip}
COMMANDS = {commands}
ROOT = "/tmp/rsna-knee"

zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(ROOT)
if PIP:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-input", *PIP], check=False)
env = dict(os.environ, PYTHONUNBUFFERED="1")
for cmd in COMMANDS:
    t0 = time.time()
    print("$ python " + " ".join(cmd), flush=True)
    ret = subprocess.run([sys.executable, "-u", *cmd], cwd=ROOT, env=env).returncode
    print(f"[exit {{ret}} after {{time.time() - t0:.0f}}s]", flush=True)
    if ret != 0:
        sys.exit(ret)
'''


def kaggle_username() -> str:
    out = subprocess.run(["kaggle", "config", "view"], capture_output=True, text=True).stdout
    for line in out.splitlines():
        if "username:" in line:
            return line.split("username:", 1)[1].strip()
    raise RuntimeError("could not determine Kaggle username; pass --user")


def make_payload() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for top in INCLUDE:
            for path in sorted((ROOT / top).rglob("*")):
                if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc":
                    zf.write(path, path.relative_to(ROOT).as_posix())
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--name", required=True, help="kernel slug, e.g. knee-inspect")
    p.add_argument("--cmd", action="append", required=True, help="script + args, run from the project root (repeatable)")
    p.add_argument("--user", default=None)
    p.add_argument("--gpu", action="store_true", help="T4 GPU (machine_shape NvidiaTeslaT4)")
    p.add_argument("--internet", action="store_true")
    p.add_argument("--pip", nargs="*", default=[], help="packages to pip install first (needs --internet)")
    p.add_argument("--dataset", action="append", default=[], help="dataset source user/slug (repeatable)")
    p.add_argument("--kernel-source", action="append", default=[], help="kernel output source user/slug")
    p.add_argument("--model-source", action="append", default=[], help="model source handle")
    p.add_argument("--no-competition", action="store_true")
    p.add_argument("--out", default=None, help="build dir (default build/kaggle/<name>)")
    p.add_argument("--push", action="store_true", help="run `kaggle kernels push` after building")
    p.add_argument("--timeout", type=int, default=None, help="max run time in seconds (push only)")
    args = p.parse_args()

    user = args.user or kaggle_username()
    out = Path(args.out) if args.out else ROOT / "build" / "kaggle" / args.name
    out.mkdir(parents=True, exist_ok=True)
    code_file = f"{args.name}.py"
    commands = [shlex.split(c) for c in args.cmd]
    (out / code_file).write_text(
        TEMPLATE.format(payload=make_payload(), pip=repr(args.pip), commands=repr(commands)), encoding="utf-8")
    meta = {
        "id": f"{user}/{args.name}",
        "title": args.name,
        "code_file": code_file,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": bool(args.gpu),
        "enable_tpu": False,
        "enable_internet": bool(args.internet),
        "dataset_sources": args.dataset,
        "competition_sources": [] if args.no_competition else [COMPETITION],
        "kernel_sources": args.kernel_source,
        "model_sources": args.model_source,
    }
    if args.gpu:
        meta["machine_shape"] = "NvidiaTeslaT4"
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    size_kb = (out / code_file).stat().st_size / 1024
    print(f"built {out} ({size_kb:.0f} KB) -> {meta['id']}")
    if args.push:
        cmd = ["kaggle", "kernels", "push", "-p", str(out)]
        if args.timeout:
            cmd += ["-t", str(args.timeout)]
        if args.gpu:
            cmd += ["--accelerator", "NvidiaTeslaT4"]
        subprocess.run(cmd, check=True)


if __name__ == "__main__":
    main()
